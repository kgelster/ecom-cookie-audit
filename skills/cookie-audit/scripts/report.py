#!/usr/bin/env python3
"""Render analyze.py findings into the client-facing markdown deliverable.

Enforces the skill's hard boundary in the output itself: the report states
OBSERVABLE FACTS and maps them to POTENTIAL EXPOSURE AREAS FOR COUNSEL REVIEW.
It never asserts a legal violation, never declares a compliance status, and never
prescribes remediation as done. Every count traces to a HAR entry.

Usage:
    report.py findings.json [--out report.md]        full markdown deliverable
    report.py findings.json --triage                 terse console summary only
"""
import argparse
import json
from collections import defaultdict

CIPA_NOTE = {
    "chat": "live-chat transcript interception — the classic §631 eavesdropping target",
    "session-replay": "keystroke/mouse capture — §631 pen-register + §632 recording theory",
    "ads-pixel": "behavioral data shipped to an ad platform for its own use — §631 third-party element",
    "analytics": "behavioral beacons to a third party — pen-register theory",
    "email-sms": "onsite behavioral tracking + form capture — pen-register theory",
    "fraud-fingerprint": "device fingerprinting — pen-register theory (courts more sympathetic to fraud-prevention purpose)",
}

DISCLAIMER = (
    "> **Scope & limits.** This is a technical diagnostic of observable browser network behavior, "
    "not legal advice and not a compliance determination. It records what third-party requests and "
    "cookies were observed in each consent state; it does not adjudicate whether any of it violates "
    "CIPA or any other law — that is counsel's call. \"Potential exposure areas\" flag where the "
    "pen-register / wiretap theories in the current CIPA wave *could* attach, for an attorney to "
    "evaluate against the party/vendor-extension exception (Graham v. Noom, Williams v. What If "
    "Holdings, Javier v. Assurance IQ) and the specific facts. No remediation has been performed."
)


def load(path):
    with open(path) as f:
        return json.load(f)


def cipa_flag(category):
    return f" — _{CIPA_NOTE[category]}_" if category in CIPA_NOTE else ""


def render(f):
    L = []
    store = f["store"]
    states = f["states"]
    cs = f["cross_state"]
    L.append(f"# Cookie-Consent & HAR Diagnostic — {store}\n")
    L.append(f"_Registry version {f.get('registry_version')}. Generated by the cookie-audit skill._\n")
    L.append(DISCLAIMER + "\n")

    # Section numbers are assigned as sections are emitted, so conditional
    # sections (a state may be absent) never leave a gap in the numbering.
    _n = [0]

    def head(title):
        _n[0] += 1
        return f"## {_n[0]}. {title}\n"

    # Scope & methodology
    L.append(head("Scope & Methodology"))
    L.append("Each consent state was captured in a fresh, isolated browser context (cleared "
             "cache/cookies/storage, no extensions) from a residential IP, then the standard funnel "
             "was exercised: home → collection → PDP → add-to-cart → cart. States captured:\n")
    for state, st in states.items():
        gpc = ""
        if state == "gpc":
            gpc = " (Sec-GPC transmitted: **{}**)".format("yes" if st.get("gpc_signal_sent") else "NO — signal absent, recapture")
        cw = "" if st.get("cookie_data_present") else "  ⚠️ **cookie data absent from this HAR — cookie findings below are blind, not clean**"
        L.append(f"- **{state}** — `{st['har_file']}`, {st['entries']} network entries{gpc}{cw}")
    L.append("")

    # Vendor inventory by state
    L.append(head("Third-Party Vendor Inventory by State"))
    for state, st in states.items():
        L.append(f"### State: `{state}` — {len(st['third_party'])} classified vendors\n")
        L.append("| Vendor | Category | Host | Requests |")
        L.append("|---|---|---|---|")
        for tp in st["third_party"]:
            L.append(f"| {tp['vendor']} | {tp['category']} | `{tp['host']}` | {tp['requests']} |")
        if st["unclassified"]:
            L.append("\n**Unclassified third parties (analyst review required):** "
                     + ", ".join(f"`{u['host']}` ({u['requests']})" for u in st["unclassified"]))
        L.append("")

    # Pre-consent firing (core)
    if "pre_consent_vendors" in cs:
        L.append(head("Pre-Consent Firing (state `none`) — core finding"))
        L.append("Third parties in CIPA-sensitive categories observed loading **before any banner "
                 "interaction**:\n")
        if cs["pre_consent_vendors"]:
            for tp in cs["pre_consent_vendors"]:
                L.append(f"- **{tp['vendor']}** (`{tp['host']}`, {tp['category']}){cipa_flag(tp['category'])}")
        else:
            L.append("- _None observed in a CIPA-sensitive category._")
        L.append("")

    # Post-decline firing
    if "post_decline_vendors" in cs:
        L.append(head("Post-Decline Firing (state `decline`)"))
        L.append("CIPA-sensitive third parties still observed **after reject-all**:\n")
        if cs["post_decline_vendors"]:
            for tp in cs["post_decline_vendors"]:
                L.append(f"- **{tp['vendor']}** (`{tp['host']}`, {tp['category']}){cipa_flag(tp['category'])}")
        else:
            L.append("- _None — decline suppressed all CIPA-sensitive marketing/analytics vendors._")
        L.append("")

    # GPC handling
    if "gpc_vendors_still_firing" in cs:
        L.append(head("GPC Handling (state `gpc`)"))
        sent = cs.get("gpc_signal_sent")
        L.append(f"GPC signal transmitted by the browser: **{'yes' if sent else 'NO — capture invalid, recapture'}**.\n")
        L.append("Note: Shopify honors GPC only where the store enabled the data-sharing opt-out for "
                 "the visitor's region; this section *observes* vendor behavior under GPC, it does not "
                 "rule on adequacy.\n")
        if cs["gpc_vendors_still_firing"]:
            L.append("CIPA-sensitive third parties still observed **with GPC present**:\n")
            for tp in cs["gpc_vendors_still_firing"]:
                L.append(f"- **{tp['vendor']}** (`{tp['host']}`, {tp['category']}){cipa_flag(tp['category'])}")
        else:
            L.append("- _None — no CIPA-sensitive vendor fired under GPC._")
        L.append("")

    # Cookies set pre-consent
    L.append(head("Cookies Observed"))
    for state, st in states.items():
        trackers = [c for c in st["cookies"] if c["tracker"]]
        if not st.get("cookie_data_present"):
            L.append(f"- **{state}**: ⚠️ no cookie data in HAR (blind — recapture).")
            continue
        if trackers:
            names = ", ".join(f"`{c['name']}` ({c['vendor']})" for c in trackers)
            L.append(f"- **{state}**: {len(trackers)} tracker cookie(s) — {names}")
        else:
            L.append(f"- **{state}**: no tracker cookies observed (functional cookies only).")
    L.append("")

    # Potential exposure areas
    L.append(head("Potential Exposure Areas for Counsel Review"))
    L.append("Framed as areas, not conclusions. An attorney should weigh each against the "
             "party/vendor-extension exception and the store's actual data-processing agreements.\n")
    seen = set()
    for bucket in ("pre_consent_vendors", "post_decline_vendors", "gpc_vendors_still_firing"):
        for tp in cs.get(bucket, []):
            key = (tp["vendor"], tp["category"])
            if key in seen:
                continue
            seen.add(key)
            where = bucket.replace("_vendors", "").replace("_", "-")
            L.append(f"- **{tp['vendor']}** ({tp['category']}) observed in `{where}`{cipa_flag(tp['category'])}")
    if not seen:
        L.append("- _No CIPA-sensitive vendor observed pre-consent, post-decline, or under GPC._")
    L.append("")

    # Reproducibility
    L.append(head("Limitations & Reproducibility"))
    L.append("- Findings reflect the captured session; a store can change tags at any time. Re-run "
             "`capture.py` + `analyze.py` to reproduce.\n"
             "- Only classified vendors are named authoritatively; unclassified hosts are flagged for "
             "review, never guessed.\n"
             "- Remediation (e.g. consent-gating scripts behind the CMP) is separate scoped work, "
             "performed only on counsel/client direction.")
    return "\n".join(L)


def triage(f):
    print(f"\n=== TRIAGE: {f['store']} ===")
    cs = f["cross_state"]
    for label, key in [("pre-consent (none)", "pre_consent_vendors"),
                       ("post-decline", "post_decline_vendors"),
                       ("under GPC", "gpc_vendors_still_firing")]:
        if key in cs:
            v = cs[key]
            if v:
                names = ", ".join(f"{t['vendor']}[{t['category']}]" for t in v)
                print(f"  {label}: {len(v)} CIPA-sensitive -> {names}")
            else:
                print(f"  {label}: clean (0 CIPA-sensitive)")
    for state, st in f["states"].items():
        if not st.get("cookie_data_present"):
            print(f"  ⚠️ state '{state}': HAR has NO cookie data — cookie findings blind.")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("findings", help="findings.json from analyze.py")
    ap.add_argument("--out", default=None, help="Write markdown here (default: stdout)")
    ap.add_argument("--triage", action="store_true", help="Terse console summary instead of full report")
    args = ap.parse_args()

    f = load(args.findings)
    if args.triage:
        triage(f)
        return
    md = render(f)
    if args.out:
        with open(args.out, "w") as out:
            out.write(md)
        print(f"Wrote {args.out}")
    else:
        print(md)


if __name__ == "__main__":
    main()
